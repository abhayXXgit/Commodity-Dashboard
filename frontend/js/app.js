  /* ------------------------------------------------------------- filters */
  function bindFilters() {
    const cm = U.el('fCommodity'), pv = U.el('fProvider'), pr = U.el('fProduct');
    if (!cm) return;
    const m = state.masters;
    cm.innerHTML = m.commodities.map(c =>
      `<option value="${c.code}">${U.esc(c.name)}</option>`).join('');
    cm.value = state.filters.commodity;
    function fillDependent() {
      const c = cm.value;
      const provs = m.providers.filter(p =>
        m.products.some(x => x.commodity === c) || p.code);
      pv.innerHTML = '<option value="">All providers</option>' +
        m.providers.map(p => `<option value="${p.code}">${U.esc(p.name)}</option>`).join('');
      pr.innerHTML = '<option value="">All products</option>' +
        m.products.filter(p => p.commodity === c)
          .map(p => `<option value="${p.code}">${U.esc(p.name)}${p.grade ? ' — ' + U.esc(p.grade) : ''}</option>`).join('');
      const h = m.headline[c];
      if (h) { pv.value = h.provider || ''; pr.value = h.product || ''; }
      state.filters.provider = pv.value; state.filters.product = pr.value;
    }
    fillDependent();
    cm.onchange = () => { state.filters.commodity = cm.value; fillDependent(); renderHistorical(); };
    pv.onchange = () => { state.filters.provider = pv.value; renderHistorical(); };
    pr.onchange = () => { state.filters.product = pr.value; renderHistorical(); };
    document.querySelectorAll('#periodSeg button').forEach(b => {
      b.onclick = () => {
        document.querySelectorAll('#periodSeg button').forEach(x => x.classList.remove('active'));
        b.classList.add('active');
        state.filters.period = b.dataset.period;
        renderHistorical();
      };
    });
  }

