  async function submitQuote(ev) {
    ev.preventDefault();
    const f = new FormData(ev.target);
    const body = Object.fromEntries(f.entries());
    ['price', 'freight', 'premium', 'tax_pct', 'moq_mt'].forEach(k => {
      if (body[k] === '') delete body[k]; else if (body[k] != null) body[k] = parseFloat(body[k]);
    });
    if (body.delivery_days === '') delete body.delivery_days;
    else if (body.delivery_days) body.delivery_days = parseInt(body.delivery_days, 10);
    Object.keys(body).forEach(k => { if (body[k] === '') delete body[k]; });
    try {
      await API.createQuote(body);
      U.toast('Quotation saved and benchmarked', 'ok');
      ev.target.reset();
      renderQuotes();
    } catch (e) { U.toast('Could not save quote: ' + e.message, 'err'); }
  }
